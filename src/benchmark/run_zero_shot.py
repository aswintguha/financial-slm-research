"""
Modular Model-Specific Native Chat-Template Benchmark Runner for Phase 05.

Core Protocol Constraints:
1. Native Chat Template Mandatory:
   - Queries tokenizer.chat_template. If absent or None, raises an explicit ConfigurationError.
   - Strictly forbids silent fallback to raw prompting or synthetic wrapper invention.
2. Frozen Semantic Prompt Preservation:
   - Exactly preserves prompt text generated by format_template_a, format_template_b, or format_template_c.
   - Wraps the unaltered text into a single-turn user message: [{"role": "user", "content": prompt_text}].
3. Generation Prompt & Deterministic Decoding:
   - Invokes tokenizer.apply_chat_template(messages, tokenize=True, add_generation_prompt=True).
   - Generates with max_new_tokens=32, temperature=0.0, do_sample=False, bfloat16 on MPS.
4. Parsing & Fallback Compliance:
   - Applies strict case-sensitive full-string parser: ^\\s*\\[FORECAST:\\s*([+-]?\\d+(?:\\.\\d+)?)\\]\\s*$.
   - Diagnostic fallback preserved, scored as is_valid=False under primary ranking.
"""

import sys
import os
import time
import math
from typing import Dict, Any, List, Optional
import torch

# Ensure benchmark modules are on path
sys.path.append(os.path.abspath("src/benchmark"))
from prompt_templates import format_template_a, format_template_b, format_template_c
from output_parser import parse_model_output

class NativeChatTemplateError(Exception):
    """Raised when a tokenizer lacks a native chat template."""
    pass

def apply_model_chat_template(
    tokenizer: Any,
    prompt_text: str,
    add_generation_prompt: bool = True
) -> Any:
    """
    Applies the tokenizer's native chat template.
    Halts with NativeChatTemplateError if chat_template is missing or None.
    """
    if not hasattr(tokenizer, "chat_template") or tokenizer.chat_template is None:
        raise NativeChatTemplateError(
            f"Tokenizer '{getattr(tokenizer, 'name_or_path', type(tokenizer))}' does not expose a native chat_template. "
            f"Per Phase 05 protocol, silent fallback to raw prompting or improvised wrappers is strictly forbidden."
        )

    messages = [{"role": "user", "content": prompt_text}]
    encoded = tokenizer.apply_chat_template(
        messages,
        tokenize=True,
        add_generation_prompt=add_generation_prompt,
        return_tensors="pt"
    )
    return encoded

def run_single_inference(
    model: Any,
    tokenizer: Any,
    prompt_text: str,
    origin_price: float,
    template_type: str = "Template_A",
    device: str = "mps",
    max_new_tokens: int = 32
) -> Dict[str, Any]:
    """
    Executes a single deterministic generation using the model's native chat template.
    """
    # 1. Apply native chat template
    encoded = apply_model_chat_template(tokenizer, prompt_text, add_generation_prompt=True)
    encoded = encoded.to(device)
    input_len = encoded.shape[1]

    # Ensure pad token
    pad_token_id = tokenizer.pad_token_id
    if pad_token_id is None:
        pad_token_id = tokenizer.eos_token_id

    # 2. Synchronized timing
    if device == "mps" and torch.backends.mps.is_available():
        torch.mps.synchronize()
    t0 = time.perf_counter()

    with torch.no_grad():
        gen_out = model.generate(
            input_ids=encoded,
            max_new_tokens=max_new_tokens,
            temperature=0.0,
            do_sample=False,
            pad_token_id=pad_token_id
        )
        if device == "mps" and torch.backends.mps.is_available():
            torch.mps.synchronize()

    t_gen = time.perf_counter() - t0

    # 3. Slice newly generated tokens
    new_tokens = gen_out[0][input_len:]
    num_tokens = len(new_tokens)
    raw_text = tokenizer.decode(new_tokens, skip_special_tokens=True).strip()

    # 4. Strict Parsing
    parsed = parse_model_output(
        raw_text=raw_text,
        template_type=template_type,
        origin_price=origin_price
    )

    return {
        "raw_text": raw_text,
        "input_tokens": input_len,
        "generated_tokens": num_tokens,
        "generation_time_sec": t_gen,
        "tokens_per_sec": (num_tokens / t_gen) if t_gen > 0 else 0.0,
        "parsed": parsed
    }

